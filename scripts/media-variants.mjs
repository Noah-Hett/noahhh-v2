#!/usr/bin/env node
// Regenerate src/content/mediaVariants.ts from the optimizer manifests
// (.media-tmp/<slug>/manifest.json, written by optimize-media.mjs), so
// Project pages know which widths/formats each R2 image has.
// Usage: node scripts/media-variants.mjs   (run after optimize-media.mjs)
// Covers are skipped: they are served from public/posters, not R2.
// Upload every listed variant to R2 before deploying a page that uses it.
import fs from 'node:fs';
import path from 'node:path';

const root = '.media-tmp';
const groups = [];
for (const slug of fs.readdirSync(root).sort()) {
  const file = path.join(root, slug, 'manifest.json');
  if (!fs.existsSync(file)) continue;
  const m = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const out of m.outputs ?? []) {
    if (out.cover) continue;
    // Only files still in .media-tmp: a manifest can list outputs from an
    // earlier run that were since dropped (and never uploaded).
    const pick = (fmt) =>
      out.produced
        .filter((p) => p.format === fmt && fs.existsSync(path.join(root, slug, p.file)))
        .sort((a, b) => a.width - b.width)
        .map((p) => [p.url, p.width]);
    const avif = pick('avif');
    if (avif.length) groups.push({ avif, webp: pick('webp') });
  }
}

const body = `// GENERATED by scripts/media-variants.mjs from the optimizer manifests —
// do not edit by hand. Every responsive variant on R2 for each Project
// image, keyed by any of its AVIF URLs (projects.ts references one).
export type MediaVariants = { avif: [string, number][]; webp: [string, number][] };

const GROUPS: MediaVariants[] = ${JSON.stringify(groups, null, 2)};

export const MEDIA_VARIANTS: ReadonlyMap<string, MediaVariants> = new Map(
  GROUPS.flatMap((g) => g.avif.map(([url]) => [url, g] as const)),
);
`;
fs.writeFileSync('src/content/mediaVariants.ts', body);
console.log(`${groups.length} images → src/content/mediaVariants.ts`);
